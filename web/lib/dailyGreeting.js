function hash(value) {
  let result = 0
  for (let i = 0; i < value.length; i += 1) result = ((result << 5) - result + value.charCodeAt(i)) | 0
  return Math.abs(result)
}

export function firstName(fullName) {
  const value = String(fullName || '').trim()
  return value ? value.split(/\s+/)[0] : 'друг'
}

export function makeDailyGreeting(fullName, now = new Date()) {
  const name = firstName(fullName)
  const hour = now.getHours()
  const period = hour >= 5 && hour < 12 ? 'morning' : hour < 18 ? 'day' : hour < 23 ? 'evening' : 'night'
  const dayKey = `${now.getFullYear()}-${now.getMonth() + 1}-${now.getDate()}-${name}`
  const seed = hash(dayKey)
  const phrase = greetings[period][seed % greetings[period].length].replace('{name}', name)
  const tip = tips[(seed * 7 + now.getDate()) % tips.length]
  return { phrase, tip }
}
